#
#  机制（同 make_zhc.ps1 的三种，再加"常量"）：
#    常量  -> 内联 常量 类型 中文名 = std::原名;
#    类型  -> 使用 中文名 = std::原名;
#    函数  -> 模板 <类型名... 参数> 自动 中文名(参数&&... 值) { 返回 std::原名(...); }
#
#  用法：powershell -File tools\make_zhalias.ps1 -Header numbers
# ============================================================================
