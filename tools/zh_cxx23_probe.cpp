// ============================================================================
//  zh_cxx23_probe.cpp —— §17.66 的 C++23 探针（手工跑，暂未进闸门）
//
//  为什么需要它：
//    本工程（生成器 L7568）**写死 `-std=c++20`** ⇒ 所有 `#if _HAS_CXX23` 里的护栏
//    **闸门守不到**。而 <跨度> 的 crbegin / crend 正是 C++23-only 成员：
//    它们的中文名在抄来那层、英文转发只能写进 deriveExtra 并用同一个宏护住。
//    这类护栏如果没人编过，就等于不存在（本项目的老规矩：护栏不进闸门 = 护栏不存在）。
//
//  跑法（在仓库根）：
//    build\Release\bin\chinese++.exe -std=c++23 -isystem zhstdlib -fsyntax-only tools\zh_cxx23_probe.cpp
//  期望：exit 0。
//
//  ⚠ 待办：把它接进 tools\regen_zhstdlib.ps1（与其它探针同批），
//    这样以后任何 `#if _HAS_CXX23` 的转发都不会再"只写不验"。
// ============================================================================
#include <跨度>

int main() {
    int raw[3] = {1, 2, 3};
    标准::跨度<int> s(raw);

    // C++20 就有的两条：中文名 + 英文名
    自动 a  = s.反向开始();
    自动 b  = s.rbegin();
    自动 ea = s.反向结束();
    自动 eb = s.rend();

    // C++23 才有的两条：中文名在抄来那层，英文名由 deriveExtra 用 #if _HAS_CXX23 转发
    自动 c  = s.常量反向开始();
    自动 d  = s.crbegin();
    自动 ec = s.常量反向结束();
    自动 ed = s.crend();

    整数 错 = (*a == 3 ? 0 : 1) + (*b == 3 ? 0 : 1) + (*c == 3 ? 0 : 1) + (*d == 3 ? 0 : 1);
    错 = 错 + (ea == eb ? 0 : 1) + (ec == ed ? 0 : 1);
    返回 错;
}
